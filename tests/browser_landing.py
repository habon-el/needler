"""Read-only landing smoke test; never changes a saved customer design."""
import base64
from pathlib import Path
from browser_helpers import call, ev, wait

output=Path(__file__).resolve().parents[1]/'outputs'
call('Page.bringToFront',{})
call('Emulation.setFocusEmulationEnabled',{'enabled':True})
call('Emulation.setDeviceMetricsOverride',{'width':1440,'height':1000,'deviceScaleFactor':1,'mobile':False})
old=ev('performance.timeOrigin')
call('Page.navigate',{'url':'http://127.0.0.1:5050/'})
wait(f'performance.timeOrigin !== {old}')
wait('document.readyState==="complete" && !!document.querySelector("#demoCanvas")')
assert ev('document.querySelector("h1").textContent.includes("Your ideas.")')
assert ev('document.documentElement.scrollWidth<=innerWidth')
ev('document.querySelector("[data-stage=plan]").click();document.querySelector("[data-colour=\\"#365b91\\"]").click()')
assert ev('document.querySelector("#demoMode").textContent==="THREAD PLAN"')
ev('document.querySelector("[data-stage=stitches]").click()')
wait('!document.querySelector("#demoPlay").disabled')
ev('document.querySelector("#demoPlay").click()')
wait('Number(document.querySelector("#demoProgress").value)>0')
ev('document.querySelector("#demoPlay").click()')
assert ev('document.querySelector("#demoPlay").textContent==="Play stitches"')
ev('document.querySelector("#demoProgress").value=100;document.querySelector("#demoProgress").dispatchEvent(new Event("input"));document.querySelector("#how-it-works").scrollIntoView({behavior:"instant"})')
output.joinpath('landing-demo-20260926.jpg').write_bytes(base64.b64decode(call('Page.captureScreenshot',{'format':'jpeg','quality':60})['result']['data']))
call('Emulation.setEmulatedMedia',{'features':[{'name':'prefers-reduced-motion','value':'reduce'}]})
ev('document.querySelector("#demoPlay").click()')
assert ev('document.querySelector("#demoProgress").value==="100"')
assert ev('document.querySelector("#demoStatus").textContent.includes("reduced motion")')
ev('document.querySelector(".faq-list summary").focus()')
call('Input.dispatchKeyEvent',{'type':'keyDown','key':'Enter','code':'Enter','windowsVirtualKeyCode':13,'text':'\r','unmodifiedText':'\r'})
call('Input.dispatchKeyEvent',{'type':'keyUp','key':'Enter','code':'Enter','windowsVirtualKeyCode':13})
wait('document.querySelector(".faq-list details").open')
call('Emulation.setDeviceMetricsOverride',{'width':390,'height':844,'deviceScaleFactor':1,'mobile':True})
ev('scrollTo({top:0,behavior:"instant"})')
assert ev('document.documentElement.scrollWidth<=innerWidth')
output.joinpath('landing-mobile-20260926.jpg').write_bytes(base64.b64decode(call('Page.captureScreenshot',{'format':'jpeg','quality':65})['result']['data']))
# Failure and retry without calling the generator or modifying any design.
old=ev('performance.timeOrigin');call('Page.reload',{})
wait(f'performance.timeOrigin !== {old}')
wait('document.readyState==="complete" && !!document.querySelector("#demoPlay")')
ev('window.originalFetch=window.fetch;window.fetch=()=>Promise.reject(new Error("test failure"));document.querySelector("[data-stage=stitches]").click()')
wait('!document.querySelector("#demoRetry").hidden')
assert ev('document.querySelector("#demoStatus").textContent.includes("unaffected")')
ev('window.fetch=window.originalFetch;document.querySelector("#demoRetry").click()')
wait('!document.querySelector("#demoPlay").disabled')
ev('document.querySelector(".site-header .button").click()')
wait('location.pathname==="/designs" && !!document.querySelector("#newDesign")')
call('Emulation.setEmulatedMedia',{'features':[]})
print('PASS: landing, three demo steps, colour, actual playback, pause/scrub, reduced motion, keyboard FAQ, 390px reflow, load failure/retry, studio link. No saved design changes.')
