wait('!document.querySelector("#inkOnly").disabled')
assert ev('document.querySelectorAll("input[name=stitch-choice-ink_bean_repeats]")[0].checked')
ev('document.querySelector("[data-topic=borders]").click()')
assert ev('document.querySelector("input[name=stitch-choice-border_style][value=satin]").disabled')
