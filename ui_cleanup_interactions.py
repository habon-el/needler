"""Exercise the real local UI using only new verification designs."""
import json
import time
from pathlib import Path
from ui_cleanup_browser import call, go, wait, ev, shot

proof = []
def check(name, expression):
    assert ev(expression), name
    proof.append(name)
    print('PASS '+name, flush=True)

def click(id):
    ev('document.getElementById('+json.dumps(id)+').click()')

def field(id, value):
    ev('(()=>{const e=document.getElementById('+json.dumps(id)+');e.value='+json.dumps(value)+';e.dispatchEvent(new Event("input",{bubbles:true}));})()')

call('Page.enable')
call('Emulation.setDeviceMetricsOverride',dict(width=1366,height=768,deviceScaleFactor=1,mobile=False))
cases = json.loads(Path('ui-cleanup-cases.json').read_text())
go('/text/new')
wait('!!window.DesignWorkflow')
check('new editor starts with empty words', 'document.getElementById("letteringWords").value===""')
check('new editor is unsaved', 'document.getElementById("workflowSaved").textContent==="Unsaved changes"')
check('closed settings fit 1366x768', 'document.querySelector(".inspector").scrollHeight<=document.querySelector(".inspector").clientHeight+1')
click('stitch')
check('empty words focus the existing validation error', 'document.activeElement.id==="letteringWords" && document.getElementById("status").textContent.includes("Enter your words")')
ev('DesignWorkflow.show("edit")')
field('letteringWords','UI check')
field('nativeWidth','80')
field('nativeHeight','3')
click('stitch')
check('below-range size is still blocked', 'document.getElementById("nativeHeight").getAttribute("aria-invalid")==="true" && document.getElementById("workflowDownload").disabled')
ev('DesignWorkflow.show("edit")')
field('nativeHeight','5')
click('stitch')
check('generation uses one primary action', 'document.getElementById("stitch").disabled && document.body.dataset.workflow==="check"')
wait('embroideryStudio.hasPlayback() && !document.getElementById("workflowNext").disabled', 90)
check('successful check leaves warnings visible', 'document.getElementById("workflowSafety").checkVisibility() && document.getElementById("routeSummary").checkVisibility()')
check('no duplicate visible save/check actions', 'Array.from(document.querySelectorAll("button")).filter(e=>e.checkVisibility()&&e.textContent.trim()==="Save design").length===1 && !document.getElementById("nativeCheck").checkVisibility()')
click('workflowNext')
if ev('!document.getElementById("save").disabled'):
    check('approval still required before native download', 'document.getElementById("workflowDownload").disabled')
    click('save')
    wait('!document.getElementById("workflowDownload").disabled')
check('saved state is confirmed, not assumed on click', 'document.getElementById("workflowSaved").textContent==="Saved"')
field('workflowFormat','pes')
ev('document.getElementById("workflowFormat").dispatchEvent(new Event("change"))')
check('single file selector changes download label','document.getElementById("workflowDownload").textContent==="Download PES"')
# Record the existing download handler's fetched blob, avoiding a file-name
# collision in the user's download directory. Server downloads are also read
# back separately by ui_cleanup_verify.py.
ev('window.uiBlobSizes=[];window.uiCreateURL=URL.createObjectURL;URL.createObjectURL=b=>{uiBlobSizes.push(b.size);return uiCreateURL(b)}')
call('Browser.setDownloadBehavior', {'behavior':'deny'})
click('workflowDownload')
wait('window.uiBlobSizes.length===1')
check('native download handler fetched a nonempty checked file', 'uiBlobSizes[0]>500')
ev('URL.createObjectURL=uiCreateURL;DesignWorkflow.show("edit")')
field('letteringWords','UI changed')
check('edit revokes downloads and labels stale stitches', 'document.getElementById("workflowSaved").textContent==="Unsaved changes" && document.getElementById("workflowDownload").disabled && document.getElementById("stitch").textContent==="Update stitches"')
click('undo')
check('undo remains owned by the text controller', 'document.getElementById("letteringWords").value==="UI check" && document.getElementById("workflowDownload").disabled')
# No pending request or customer design is changed by these navigation checks.
ev('window.onbeforeunload=null')
go(cases['image']['page'])
wait('!!window.DesignWorkflow && !embroideryStudio.isBusy()')
check('image essentials fit with Expert settings closed', 'document.querySelector(".inspector").scrollHeight<=document.querySelector(".inspector").clientHeight+1')
click('workflowColours')
check('existing image colour controls remain reachable', 'document.getElementById("workflowExpert").open && document.getElementById("topic-colours").checkVisibility()')
ev('DesignWorkflow.show("edit");document.getElementById("workflowExpert").open=false')
check('one pair of image size fields', 'document.querySelectorAll("#canvasWidth").length===1 && document.querySelectorAll("#canvasHeight").length===1')
# Explicitly save this generated test rectangle only, to verify the success label.
click('save')
wait('!embroideryStudio.isBusy() && document.getElementById("workflowSaved").textContent==="Saved"')
check('image save confirmation reaches the header', 'document.getElementById("workflowSaved").textContent==="Saved"')
go('/designs')
wait('document.querySelectorAll(".design-card").length>0')
check('equal library start choices', '(()=>{const r=Array.from(document.querySelectorAll(".start-choices .button")).map(e=>e.getBoundingClientRect());return r.length===2&&Math.abs(r[0].width-r[1].width)<1&&r.every(e=>e.height>=50)})()')
check('generated IDs are not card titles','Array.from(document.querySelectorAll(".design-card h2")).every(e=>!/Untitled design|[a-f0-9]{20}/i.test(e.textContent))')
source = cases['image']['page'].rsplit('/',1)[-1]
ev('window.uiCard=Array.from(document.querySelectorAll(".design-card")).find(e=>e.dataset.id==='+json.dumps(source)+')')
check('test image present in library', '!!window.uiCard')
ev('uiCard.querySelector(".card-menu").open=true;Array.from(uiCard.querySelectorAll("button")).find(e=>e.textContent==="Rename").click()')
check('rename is in place with input focus', '!!uiCard.querySelector(".card-rename") && document.activeElement===uiCard.querySelector(".card-rename input") && !document.getElementById("renameDesign").open')
ev('uiCard.querySelector(".card-rename input").value="";uiCard.querySelector(".card-rename").requestSubmit()')
check('empty rename gives inline feedback','uiCard.querySelector(".card-rename [role=alert]").textContent.includes("Enter a name")')
ev('uiCard.querySelector(".card-rename input").dispatchEvent(new KeyboardEvent("keydown",{key:"Escape",bubbles:true}))')
check('Escape cancels rename without changing the card', '!document.querySelector(".card-rename")')
ev('uiCard.querySelector(".card-menu").open=true;Array.from(uiCard.querySelectorAll("button")).find(e=>e.textContent==="Rename").click();uiCard.querySelector(".card-rename input").value="UI proof rectangle";uiCard.querySelector(".card-rename").requestSubmit()')
wait('document.getElementById("libraryStatus").textContent==="Name saved."')
check('inline rename uses the existing persistence API','Array.from(document.querySelectorAll(".design-card h2")).some(e=>e.textContent==="UI proof rectangle")')
field('librarySearch','ui-no-matching-design-987654')
check('no-results search is recoverable','document.getElementById("designGrid").textContent.includes("No designs match") && !document.getElementById("clearSearch").hidden')
click('clearSearch')
check('clear restores list and search focus','document.querySelectorAll(".design-card").length>0 && document.activeElement.id==="librarySearch"')
go(cases['text']['page']);wait('!!window.DesignWorkflow && embroideryStudio.hasPlayback()')
ev('DesignWorkflow.show("edit")')
call('Emulation.setDeviceMetricsOverride',dict(width=390,height=844,deviceScaleFactor=1,mobile=False))
check('narrow screen keeps the step navigation', 'document.getElementById("workflowSteps").checkVisibility()')
shot('after-narrow')
call('Emulation.setDeviceMetricsOverride',dict(width=1366,height=768,deviceScaleFactor=1,mobile=False))
call('Emulation.setEmulatedMedia',{'features':[{'name':'prefers-reduced-motion','value':'reduce'},{'name':'forced-colors','value':'active'}]})
check('keyboard navigation and high contrast retain real buttons', 'document.querySelector("[data-workflow=check]").tagName==="BUTTON" && document.querySelector("[data-workflow=check]").checkVisibility()')
call('Emulation.setEmulatedMedia',{'features':[]})
go('/text/new');wait('!!window.DesignWorkflow')
field('letteringWords','UI recovery')
field('nativeWidth','100')
ev('window.uiFetch=window.fetch;window.fetch=(url,options)=>String(url).endsWith("/lettering/native/check")?Promise.reject(Error("Offline test: retry when connected.")):uiFetch(url,options)')
click('stitch')
wait('!document.getElementById("stitch").disabled')
check('network failure stays in the workspace','document.getElementById("status").textContent.includes("Offline test") && document.getElementById("workflowDownload").disabled')
check('failed check remains retryable','document.getElementById("stitch").checkVisibility() && !document.getElementById("stitch").disabled')
ev('window.fetch=uiFetch;DesignWorkflow.show("edit")')
# Hold a valid prior result in the test browser; a later edit must discard it.
ev('(async()=>{window.uiPrior=await (await fetch('+json.dumps(cases['text']['url'].replace('/download/',''))+')).json()})()')
ev('window.fetch=(url,options)=>String(url).endsWith("/lettering/native/check")?new Promise(resolve=>{window.uiRelease=()=>resolve(new Response(JSON.stringify(uiPrior),{status:200,headers:{"Content-Type":"application/json"}}))}):uiFetch(url,options)')
click('stitch')
check('slow check is pending, not downloadable','document.getElementById("stitch").disabled && document.getElementById("workflowDownload").disabled')
ev('DesignWorkflow.show("edit")')
field('letteringWords','UI newer words')
ev('uiRelease()')
wait('!document.getElementById("stitch").disabled')
check('late response cannot replace newer words','document.getElementById("letteringWords").value==="UI newer words" && !embroideryStudio.hasPlayback() && document.getElementById("workflowDownload").disabled')
ev('window.fetch=uiFetch')
# Simulate a failed approval response; no backend data is changed.
ev('nativeLettering.load({...uiPrior,approved:false})')
wait('embroideryStudio.hasPlayback() && !document.getElementById("save").disabled')
ev('window.fetch=(url,options)=>String(url).endsWith("/approve")?Promise.reject(Error("Save interrupted.")):uiFetch(url,options)')
click('save')
wait('document.getElementById("status").textContent.includes("Save interrupted")')
check('failed approval never shows Saved','document.getElementById("workflowSaved").textContent==="Unsaved changes" && document.getElementById("workflowDownload").disabled')
ev('window.fetch=uiFetch')
Path('ui-interaction-results.json').write_text(json.dumps({'passed':len(proof),'checks':proof},indent=2))
print(f'{len(proof)} browser checks passed',flush=True)
